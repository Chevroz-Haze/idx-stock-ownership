export type KseiInvestorClass =
  | 'CP' // Corporate (Perusahaan)
  | 'ID' // Individual (Individu)
  | 'IB' // Financial Institution / Bank (Bank)
  | 'IS' // Insurance (Asuransi)
  | 'MF' // Mutual Fund (Reksa Dana)
  | 'PF' // Pension Fund (Dana Pensiun)
  | 'SC' // Securities Company (Perusahaan Efek)
  | 'FD' // Foundation (Yayasan)
  | 'OT'; // Others / Sovereign / Nominee

export type DomicileStatus = 'Lokal' | 'Asing';

export type StructuralSignal =
  | 'Clean Accumulation'
  | 'Register Tightening'
  | 'Distribution / Exit'
  | 'New >=1% Entry'
  | 'Below 1% Floor Exit'
  | 'Stable Core';

export interface ShareholderPosition {
  id: string;
  ticker: string;
  investorName: string;
  investorClass: KseiInvestorClass;
  domicile: DomicileStatus;
  conglomerateGroup: string | null;
  custodianName: string;
  // Monthly periods: Sep 2026 (Current), Aug 2026 (Prev), Jul 2026 (2M Ago)
  sharesCurrent: number;
  pctCurrent: number;
  sharesPrev: number;
  pctPrev: number;
  sharesTwoMonthsAgo: number;
  pctTwoMonthsAgo: number;
  isController: boolean;
  isNominee: boolean;
  filingDate: string;
  signal: StructuralSignal;
}

